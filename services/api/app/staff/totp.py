"""RFC 6238 time-based one-time passwords.

Implemented over the standard library so the console carries no extra runtime
dependency. Secrets are base32 (RFC 4648) as generated by an authenticator app;
codes are HMAC-SHA1, six digits, on a 30-second step, compared in constant time.

A digest and code are never logged.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import struct
import time

# RFC 6238 defaults, matching the SHA-1 / 6-digit / 30-second profile every
# authenticator app uses.
DIGITS = 6
STEP_SECONDS = 30
_WINDOW_STEPS = 1  # accept the adjacent step for clock drift


def _decode_secret(secret: str) -> bytes:
    """Decode a base32 TOTP secret, tolerating padding and lower case."""
    normalised = secret.strip().replace(" ", "").upper()
    padding = "=" * (-len(normalised) % 8)
    try:
        return base64.b32decode(normalised + padding, casefold=True)
    except (binascii.Error, ValueError) as exc:
        raise ValueError("invalid TOTP secret") from exc


def _hotp(secret: bytes, counter: int) -> str:
    digest = hmac.new(secret, struct.pack(">Q", counter), hashlib.sha1).digest()
    offset = digest[-1] & 0x0F
    truncated = struct.unpack(">I", digest[offset : offset + 4])[0] & 0x7FFFFFFF
    return str(truncated % (10**DIGITS)).zfill(DIGITS)


def generate(secret: str, *, at: float | None = None) -> str:
    """Return the code for the current step. Used by tests and provisioning."""
    counter = int((at if at is not None else time.time()) // STEP_SECONDS)
    return _hotp(_decode_secret(secret), counter)


def verify(secret: str, code: str, *, at: float | None = None) -> bool:
    """Whether ``code`` matches the current step, allowing one step of drift."""
    if not secret or not code:
        return False
    submitted = code.strip().replace(" ", "")
    if not submitted.isdigit() or len(submitted) != DIGITS:
        return False
    step = int((at if at is not None else time.time()) // STEP_SECONDS)
    key = _decode_secret(secret)
    # Compare against every candidate without an early exit so the timing does
    # not reveal which step matched.
    matched = False
    for delta in range(-_WINDOW_STEPS, _WINDOW_STEPS + 1):
        candidate = _hotp(key, step + delta)
        if hmac.compare_digest(candidate, submitted):
            matched = True
    return matched
